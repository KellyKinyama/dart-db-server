/// Oracle DDL/DML + type-enforcement gaps closed in the round-24..26 sweeps:
/// MINUS set operator, IDENTITY columns, DEFAULT ON NULL, MERGE ... DELETE,
/// NUMBER(p,s) scale rounding, NUMBER(p) precision and VARCHAR2(n) length
/// enforcement.
library;

import 'package:dart_db_server/dart_db_server.dart';
import 'package:test/test.dart';

void main() {
  Future<Object?> scalar(Database db, String sql) async =>
      (await db.execute(sql)).rows.first.first;

  test('MINUS is a synonym for EXCEPT', () async {
    final db = await Database.open(null);
    try {
      await db.execute('CREATE TABLE t (g NUMBER)');
      await db.execute('INSERT INTO t VALUES (1), (2), (3)');
      final r = await db.execute('SELECT g FROM t MINUS SELECT 1 FROM t');
      expect(r.rows.map((e) => e.first).toList()..sort(), [2, 3]);
    } finally {
      await db.close();
    }
  });

  test('GENERATED AS IDENTITY auto-populates like AUTOINCREMENT', () async {
    final db = await Database.open(null);
    try {
      await db.execute(
          'CREATE TABLE t (id NUMBER GENERATED ALWAYS AS IDENTITY, v NUMBER)');
      await db.execute('INSERT INTO t (v) VALUES (10)');
      await db.execute('INSERT INTO t (v) VALUES (20)');
      final r = await db.execute('SELECT id FROM t ORDER BY v');
      expect(r.rows.map((e) => e.first).toList(), [1, 2]);
    } finally {
      await db.close();
    }
  });

  test('GENERATED BY DEFAULT AS IDENTITY with sequence options parses',
      () async {
    final db = await Database.open(null);
    try {
      await db.execute('CREATE TABLE t (id NUMBER GENERATED BY DEFAULT ON NULL '
          'AS IDENTITY (START WITH 1 INCREMENT BY 1), v NUMBER)');
      await db.execute('INSERT INTO t (v) VALUES (5)');
      expect(await scalar(db, 'SELECT id FROM t'), 1);
    } finally {
      await db.close();
    }
  });

  test('DEFAULT ON NULL applies the default expression', () async {
    final db = await Database.open(null);
    try {
      await db.execute('CREATE TABLE t (a NUMBER DEFAULT ON NULL 7, b NUMBER)');
      await db.execute('INSERT INTO t (b) VALUES (1)');
      expect(await scalar(db, 'SELECT a FROM t'), 7);
    } finally {
      await db.close();
    }
  });

  test('MERGE ... WHEN MATCHED THEN UPDATE ... DELETE WHERE removes rows',
      () async {
    final db = await Database.open(null);
    try {
      await db.execute('CREATE TABLE t (id NUMBER, v NUMBER)');
      await db.execute('INSERT INTO t VALUES (1, 10), (2, 20)');
      await db.execute(
          'MERGE INTO t USING (SELECT 1 id FROM dual) s ON (t.id = s.id) '
          'WHEN MATCHED THEN UPDATE SET v = 99 DELETE WHERE v > 50');
      // id=1 is updated to 99 then deleted (99 > 50); id=2 is untouched.
      final r = await db.execute('SELECT id, v FROM t ORDER BY id');
      expect(r.rows, [
        [2, 20]
      ]);
    } finally {
      await db.close();
    }
  });

  test('NUMBER(p,s) rounds to the declared scale', () async {
    final db = await Database.open(null);
    try {
      await db.execute('CREATE TABLE t (n NUMBER(5,2))');
      await db.execute('INSERT INTO t VALUES (1.239)');
      expect(await scalar(db, 'SELECT n FROM t'), 1.24);
    } finally {
      await db.close();
    }
  });

  test('NUMBER(p) rejects out-of-precision values', () async {
    final db = await Database.open(null);
    try {
      await db.execute('CREATE TABLE t (n NUMBER(3))');
      await expectLater(
        db.execute('INSERT INTO t VALUES (12345)'),
        throwsA(isA<Exception>()),
      );
    } finally {
      await db.close();
    }
  });

  test('VARCHAR2(n) rejects oversized strings', () async {
    final db = await Database.open(null);
    try {
      await db.execute('CREATE TABLE t (s VARCHAR2(3))');
      await db.execute("INSERT INTO t VALUES ('abc')");
      await expectLater(
        db.execute("INSERT INTO t VALUES ('abcdefg')"),
        throwsA(isA<Exception>()),
      );
    } finally {
      await db.close();
    }
  });
}
