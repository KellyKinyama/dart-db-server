/// Builds the native (thick OCI/OCCI) status reply for a non-query statement
/// (INSERT/UPDATE/DELETE/DDL), carrying the affected-row count that `oci8`
/// surfaces as `oci_num_rows`.
Uint8List buildNativeDmlResponse(int affected) {
  if (affected <= 0) return Uint8List.fromList(_dmlBlockZero);
  final b = Uint8List.fromList(_dmlBlock);
  b[42] = affected & 0xFF;
  b[43] = (affected >> 8) & 0xFF;
  b[44] = (affected >> 16) & 0xFF;
  b[45] = (affected >> 24) & 0xFF;
  b[120] = affected & 0xFF;
  return b;
}

/// The native "end of call, OK" status terminal a real listener returns for a
/// control call (commit / close / logoff), captured verbatim. The thin
/// `buildStatusOk` (`09 00 00`) is too short — the native client hangs on it,
/// most visibly as a stalled `oci_close` after any statement.
Uint8List buildNativeStatusOk() => Uint8List.fromList(
    const [0x09, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1d]);

